/* ============================================================
 * relations.js —— 关系边
 *
 * 为什么要单独一张表：画家、名画、签名卡各自的字段只能记「自己是什么」，
 * 记不住「和谁有关系」。而提示词组合真正吃的就是关系：
 *   创作者 →作品→ 材料 →机构     回答「这句话从哪来、能不能商用」
 *   流派   →画家 →技法           回答「为什么这两个人能融」
 *   签名卡 →派生自→ 任务模板     回答「这张卡是为谁做的」
 *
 * 边的写法刻意模仿 CIDOC CRM：谁、做了什么、对象是谁，
 * 分成独立字段而不是一句话。因为一句话没法反向索引。
 *
 * kind 取值（刻意与 PV-07 的 CRM 思路对齐）：
 *   created      创作者  → 作品      谁画的
 *   held_by      作品    → 机构      收藏在哪、能不能商用
 *   uses         作品    → 媒介      这幅画是怎么做出来的
 *   member_of    画家    → 流派      归属
 *   exemplifies  流派    → 画家      谁是这个流派的代表（比 member_of 弱）
 *   active_in    画家    → 地区      活跃地点
 *   student_of   画家    → 画家      师承（强）
 *   influenced   画家    → 画家      影响（弱，方向为 from 受 to 影响）
 *   derived_from 签名卡  → 签名卡    变形示范的母版
 *   serves       签名卡  → 任务      这张卡服务哪类诉求
 *   realizes     签名卡  → 原子模块  这张卡实际用到了哪些模块
 *   aligned_with 实体    → 来源      外部标准对齐（接 PROVENANCE）
 *
 * 边的方向统一为「派生者 → 被派生者」，方便单向下钻。
 * ============================================================ */
