/* ============================================================
 * codes.js · 全库统一编码表
 * ============================================================
 * 用户的原话（第二轮）：
 *   「你的编码是不是过于乱了？没有统一的命名？有好几种命名方式，
 *     这样没有形成系统性和统一性，也不方便后续组合呀」
 *
 * 这条批评是对的，而且指出的正是上一版设计的根本缺陷。
 * 上一版有四种长度并存：
 *
 *   P-CN-001   画家      三段，中段是国别字母
 *   AM-101     原子模块  两段，中段是类别数字
 *   AM-A-001   原子模块  三段，中段是类别字母
 *   O-01-001   光学词条  三段，中段是组号
 *   O-001      光学分组  两段
 *
 * 问题不在于「多了一种」，而在于**同一个位置放了三种不同的语义**：
 *   P-CN-001 的中段是国别，AM-A-001 的中段是类别，
 *   O-01-001 的中段是分组。三者语法相同、含义不同。
 * 于是 AM-101 与 O-001 肉眼几乎无法区分（都是「两字母+数字」），
 * 而 AM-101 与 AM-A-001 又同段不同形。组合串一旦长起来，
 * 人眼无法校验，机器也无法用一条正则解析全库。
 *
 * 本版规则（唯一真源，改这里就够）：
 *   全库统一两段：  <段码>-<三位序号>      PA-001  AM-007  OP-042
 *
 * 三条硬约定：
 *   1. 段码固定两字母，14 段两两不同且互不为前缀（由 check_codes 断言）。
 *      为什么要两字母而不是一字母：单字母段只剩 26 个可用，
 *      而「段码互不为前缀」这条约束在 26 个字母里几乎排不开
 *      —— P 与 PA、R 与 RL、S 与 SJ 一旦互为前缀就会误判段。
 *      两字母有 676 个，约束一下就能排开。
 *   2. 段码只表达「这是哪一层」，不再夹带国别/类别/组号。
 *      那些信息降级为**字段**（painter.region / atom.cat / optic.group），
 *      靠界面筛选与检索取回。理由：塞进编码会让编码长度不可控，
 *      而用户组合时需要的是「能打出来」，不是「能看出分组」。
 *      光学分组另给一段 OG，因为它与词条挤在同一段时，
 *      「OP-001 是组还是词」永远说不清。
 *   3. 旧 ID 与上一版 code 全部保留为可解析别名。
 *      用户手里已有的 AM-101 / P-IT-007 / G-01 必须继续能查能组合，
 *      否则这就是一次破坏性变更。派生规则见 legacyCode()。
 *
 * 为什么序号仍是三位：画家 205、关系边 306、原子模块 126，
 * 两位撑到 99 就撞号。三位可到 999，中途追加永不重排旧号。
 *
 * code 一旦发布不可改。改它等于让用户手里的组合串失效。
 * 新增条目只会往后追加序号，不会重排旧号。
 * ============================================================ */
